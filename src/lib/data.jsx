/** Samakan kategori ke label resmi di CATEGORIES */
export function normalizeCategory(cat) {
  if (!cat) return cat;
  const trimmed = String(cat).trim();
  if (CATEGORY_LEGACY_MAP[trimmed]) return CATEGORY_LEGACY_MAP[trimmed];
  return trimmed;
}

